PROMPT ============================================================

BEGIN
  FOR t IN (
    SELECT table_name FROM user_tables
    WHERE table_name IN (
      'PAIEMENT','FACTURE','DEMANDE_ANALYSE','ANALYSE','HOSPITALISATION',
      'ACTE_CONSULTATION','ACTE','PRESCRIPTION','MEDICAMENT','ORDONNANCE',
      'CONSULTATION','RENDEZ_VOUS','CHAMBRE','SERVICE','MEDECIN','PATIENT',
      'PERSONNE','CLINIQUE','JOURNAL_OPERATION'
    )
  ) LOOP
    EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
  END LOOP;

  FOR s IN (
    SELECT sequence_name FROM user_sequences
    WHERE sequence_name IN (
      'SEQ_CLINIQUE','SEQ_PERSONNE','SEQ_PATIENT','SEQ_MEDECIN','SEQ_SERVICE',
      'SEQ_CHAMBRE','SEQ_RDV','SEQ_CONSULTATION','SEQ_ORDONNANCE',
      'SEQ_MEDICAMENT','SEQ_ACTE','SEQ_HOSPITALISATION','SEQ_ANALYSE',
      'SEQ_DEMANDE_ANALYSE','SEQ_FACTURE','SEQ_PAIEMENT','SEQ_JOURNAL'
    )
  ) LOOP
    EXECUTE IMMEDIATE 'DROP SEQUENCE ' || s.sequence_name;
  END LOOP;
END;
