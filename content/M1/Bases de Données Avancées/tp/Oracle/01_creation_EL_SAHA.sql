CREATE TABLE CLINIQUE (
  ID_CLINIQUE       NUMBER(4)      CONSTRAINT PK_CLINIQUE PRIMARY KEY,
  NOM_CLINIQUE      VARCHAR2(80)   CONSTRAINT NN_CLINIQUE_NOM NOT NULL,
  VILLE             VARCHAR2(40)   CONSTRAINT NN_CLINIQUE_VILLE NOT NULL,
  ADRESSE           VARCHAR2(150)  CONSTRAINT NN_CLINIQUE_ADR NOT NULL,
  TELEPHONE         VARCHAR2(20),
  TYPE_CLINIQUE     VARCHAR2(20)   DEFAULT 'PRIVEE' NOT NULL,
  DATE_OUVERTURE    DATE,
  CONSTRAINT UQ_CLINIQUE_NOM_VILLE UNIQUE (NOM_CLINIQUE, VILLE),
  CONSTRAINT CK_CLINIQUE_TYPE CHECK (TYPE_CLINIQUE IN ('PUBLIQUE','PRIVEE','MIXTE'))
);

COMMENT ON TABLE CLINIQUE IS 'Etablissements de sante du reseau EL_SAHA';
COMMENT ON COLUMN CLINIQUE.TYPE_CLINIQUE IS 'PUBLIQUE, PRIVEE ou MIXTE';

CREATE TABLE PERSONNE (
  ID_PERSONNE       NUMBER(6)      CONSTRAINT PK_PERSONNE PRIMARY KEY,
  NOM               VARCHAR2(50)   CONSTRAINT NN_PERSONNE_NOM NOT NULL,
  PRENOM            VARCHAR2(50)   CONSTRAINT NN_PERSONNE_PRENOM NOT NULL,
  DATE_NAISSANCE    DATE           CONSTRAINT NN_PERSONNE_DN NOT NULL,
  SEXE              CHAR(1)        CONSTRAINT NN_PERSONNE_SEXE NOT NULL,
  ADRESSE           VARCHAR2(180),
  VILLE             VARCHAR2(40),
  TELEPHONE         VARCHAR2(20),
  EMAIL             VARCHAR2(100),
  DATE_CREATION     DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT CK_PERSONNE_SEXE CHECK (SEXE IN ('F','M')),
  CONSTRAINT CK_PERSONNE_DATE CHECK (DATE_NAISSANCE < DATE_CREATION),
  CONSTRAINT UQ_PERSONNE_EMAIL UNIQUE (EMAIL)
);

COMMENT ON TABLE PERSONNE IS 'Super-type relationnel commun aux patients et medecins';

CREATE TABLE PATIENT (
  ID_PATIENT        NUMBER(6)      CONSTRAINT PK_PATIENT PRIMARY KEY,
  ID_PERSONNE       NUMBER(6)      CONSTRAINT NN_PATIENT_PERSONNE NOT NULL,
  NUM_SECURITE_SOC  VARCHAR2(30),
  GROUPE_SANGUIN    VARCHAR2(3),
  ANTECEDENTS       VARCHAR2(500),
  ALLERGIES         VARCHAR2(500),
  PERSONNE_CONTACT  VARCHAR2(100),
  TEL_CONTACT       VARCHAR2(20),
  CONSTRAINT UQ_PATIENT_PERSONNE UNIQUE (ID_PERSONNE),
  CONSTRAINT UQ_PATIENT_NUMSS UNIQUE (NUM_SECURITE_SOC),
  CONSTRAINT FK_PATIENT_PERSONNE FOREIGN KEY (ID_PERSONNE)
    REFERENCES PERSONNE(ID_PERSONNE),
  CONSTRAINT CK_PATIENT_GROUPE CHECK
    (GROUPE_SANGUIN IN ('A+','A-','B+','B-','AB+','AB-','O+','O-'))
);

COMMENT ON TABLE PATIENT IS 'Sous-type relationnel de PERSONNE pour les patients';

