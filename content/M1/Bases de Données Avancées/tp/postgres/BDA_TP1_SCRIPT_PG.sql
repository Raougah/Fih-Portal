-- Execution dans pgAdmin > Query Tool, dans une base de donnees de TP.
-- ATTENTION : reinitialise uniquement le schema tp1_banque.
DROP SCHEMA IF EXISTS tp1_banque CASCADE;
CREATE SCHEMA tp1_banque;
SET search_path TO tp1_banque, public;

CREATE TABLE client (
    id_client INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(60) NOT NULL,
    prenom VARCHAR(60) NOT NULL,
    ville VARCHAR(60) NOT NULL,
    date_inscription DATE NOT NULL
);

CREATE TABLE compte (
    id_compte INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_client INTEGER NOT NULL REFERENCES client(id_client),
    type_compte VARCHAR(20) NOT NULL CHECK (type_compte IN ('courant','epargne')),
    solde NUMERIC(12,2) NOT NULL CHECK (solde >= 0),
    date_ouverture DATE NOT NULL,
    actif BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE operation (
    id_operation INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_compte INTEGER NOT NULL REFERENCES compte(id_compte),
    type_operation VARCHAR(20) NOT NULL CHECK (type_operation IN ('depot','retrait','virement_entrant','virement_sortant')),
    montant NUMERIC(12,2) NOT NULL CHECK (montant > 0),
    date_operation TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    commentaire TEXT
);

CREATE TABLE historique_solde (
    id_historique INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_compte INTEGER NOT NULL REFERENCES compte(id_compte),
    ancien_solde NUMERIC(12,2) NOT NULL,
    nouveau_solde NUMERIC(12,2) NOT NULL,
    date_modification TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

